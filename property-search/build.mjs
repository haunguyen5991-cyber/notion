import { readFile, writeFile } from 'node:fs/promises';
const html = await readFile(new URL('src/index.html', import.meta.url), 'utf8');
const core = await readFile(new URL('src/core.mjs', import.meta.url), 'utf8');
await writeFile(new URL('worker.mjs', import.meta.url), '// Generated by node build.mjs. Contains no credentials.\nconst HTML = ' + JSON.stringify(html) + ';\n' + core.replace(/^export /gm, '') + '\nexport default createHandler(HTML);\n');
console.log('Built standalone worker.mjs (no credentials).');
